import { createHash } from 'node:crypto';
import { mkdir, copyFile, readFile, writeFile, rm } from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const output=new URL('dist/',root);
const testing=process.env.FIVE_STARS_ENV==='test';
const storage=JSON.parse(await readFile(new URL('config/storage.json',root),'utf8'));
const endpoint=testing?storage.testUrl:storage.url;
if(!endpoint||testing&&endpoint===storage.url)throw new Error('Test storage must use its own deployed endpoint');
const config=`<script>globalThis.FIVE_STARS_STORAGE_URL=${JSON.stringify(endpoint)};globalThis.FIVE_STARS_PREVIEW=true;globalThis.FIVE_STARS_SANDBOX=${testing};</script>`;
const hash=s=>createHash('sha256').update(s).digest('hex').slice(0,12);
await rm(output,{recursive:true,force:true});await mkdir(output,{recursive:true});
for(const file of ['style.css','share-cover-v2.jpg','local-store.js','google-store.js','ballot.js'])await copyFile(new URL(`public/${file}`,root),new URL(file,output));
const versions={};for(const file of ['local-store.js','google-store.js','ballot.js'])versions[file]=hash(await readFile(new URL(`public/${file}`,root)));
const catalogVersion=hash(await readFile(new URL('data/catalog.json',root)));
const cssVersion=hash(await readFile(new URL('public/style.css',root)));
let app=await readFile(new URL('public/app.js',root),'utf8');
for(const [file,v]of Object.entries(versions))app=app.replace(`'./${file}'`,`'./${file}?v=${v}'`);
app=app.replace("'./catalog.json'",`'./catalog.json?v=${catalogVersion}'`);
await writeFile(new URL('app.js',output),app);
const html=(await readFile(new URL('public/index.html',root),'utf8')).replace('href="style.css"',`href="style.css?v=${cssVersion}"`).replace('src="app.js"',`src="app.js?v=${hash(app)}"`).replace('<script type="module"',config+'<script type="module"');
await writeFile(new URL('index.html',output),html);
await copyFile(new URL('data/catalog.json',root),new URL('catalog.json',output));
let stats=await readFile(new URL('public/stats.js',root),'utf8');
for(const[file,v]of Object.entries(versions))stats=stats.replace(`'../${file}'`,`'../${file}?v=${v}'`);
stats=stats.replace("'../catalog.json'",`'../catalog.json?v=${catalogVersion}'`);
const statsHtml=(await readFile(new URL('public/stats.html',root),'utf8')).replace('href="../style.css"',`href="../style.css?v=${cssVersion}"`).replace('src="stats.js"',`src="stats.js?v=${hash(stats)}"`).replace('<script type="module"',config+'<script type="module"');
await mkdir(new URL('stats/',output));await writeFile(new URL('stats/index.html',output),statsHtml);await writeFile(new URL('stats/stats.js',output),stats);
await mkdir(new URL('names/',output));await copyFile(new URL('public/names.html',root),new URL('names/index.html',output));
await writeFile(new URL('.nojekyll',output),'');
console.log(`Exported ${testing?'test':'production'} with its own shared storage endpoint`);

if(testing){await mkdir(new URL('qa/',output));const qa=(await readFile(new URL('test/qa.html',root),'utf8')).replace('<script type="module">',config+'<script type="module">');await writeFile(new URL('qa/index.html',output),qa);}
